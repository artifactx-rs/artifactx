//! Pieces shared by the declarative-definition builders (`build_nix` and
//! `build_guix`).
//!
//! Nix and Guix install into a prefix instead of absolute paths, so both
//! outputs carry the manifest payload as base64 and write it with one shell
//! script. Sharing that script keeps both ecosystems' installs identical to
//! each other and to the archive builders: same paths, modes, and bytes.
//! See ADR-0030.

use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};

use crate::manifest::Manifest;
use crate::ExpandedPayload;

/// Wrap embedded base64 at this many columns.
const BASE64_COLUMNS: usize = 76;

/// Render the shared payload installer.
///
/// The script installs into `$out`, which both ecosystems set for the build:
/// Nix exports the derivation output, and Guix exports it from the package
/// outputs. `base64`, `mkdir`, and `chmod` come from `PATH`; each builder
/// arranges for coreutils to be there.
pub(crate) fn render_install_script(payload: &ExpandedPayload) -> Result<String> {
    use std::collections::btree_map::Entry;

    let mut script = String::from("set -eu\nmkdir -p \"$out\"\n");

    let mut dirs = std::collections::BTreeMap::new();
    for dir in &payload.dirs {
        let Some(rel) = install_rel(&dir.rel) else {
            continue;
        };
        match dirs.entry(rel.clone()) {
            Entry::Occupied(existing) => {
                let existing_mode = *existing.get();
                if existing_mode != dir.mode {
                    bail!(
                        "two manifest directories map to $out/{rel} with different modes \
                         ({existing_mode:04o} and {:04o})",
                        dir.mode
                    );
                }
            }
            Entry::Vacant(slot) => {
                slot.insert(dir.mode);
            }
        }
    }
    for rel in dirs.keys() {
        let path = shell_path(rel)?;
        script.push_str(&format!("mkdir -p {path}\n"));
    }

    let mut seen = std::collections::BTreeSet::new();
    for file in &payload.files {
        let Some(rel) = install_rel(&file.rel) else {
            bail!(
                "installed file {:?} resolves to the output prefix itself",
                file.rel
            );
        };
        if !seen.insert(rel.clone()) {
            bail!(
                "manifest destinations collapse onto the same path under $out: {rel:?} \
                 — dropping the /usr prefix made two files share one install path"
            );
        }
        if dirs.contains_key(&rel) {
            bail!("manifest file {rel:?} maps to a path that is also a directory under $out");
        }
        let path = shell_path(&rel)?;
        script.push_str(&format!("base64 --decode > {path} <<'ARX_PAYLOAD_EOF'\n"));
        push_base64(&mut script, &file.data);
        script.push_str(&format!(
            "ARX_PAYLOAD_EOF\nchmod {:04o} {path}\n",
            file.mode
        ));
    }

    // Directory modes go last, deepest first: a manifest can declare a
    // read-only directory (0555) and the builder is unprivileged, so applying
    // it before the payload is written would fail with "Permission denied".
    // Deepest-first also keeps a restrictive mode from hiding its own children
    // while they are still being chmodded.
    for (rel, mode) in dirs.iter().rev() {
        let path = shell_path(rel)?;
        script.push_str(&format!("chmod {mode:04o} {path}\n"));
    }
    Ok(script)
}

/// Map an installed path onto the output prefix.
///
/// Nix and Guix install into `$out`, so `/usr/bin/hello` becomes
/// `$out/bin/hello`: the `usr/` segment is the system prefix these ecosystems
/// already represent with `$out`. Every other path keeps its location below
/// `$out` (`/etc/x` → `$out/etc/x`). `None` means the directory itself
/// disappears (`/usr` becomes `$out`); see ADR-0030.
fn install_rel(rel: &str) -> Option<String> {
    let rel = rel.trim_end_matches('/');
    if rel == "usr" {
        return None;
    }
    let rel = rel.strip_prefix("usr/").unwrap_or(rel);
    (!rel.is_empty()).then(|| rel.to_string())
}

/// Header comment block for manifest fields the target ecosystem cannot express.
///
/// `prefix` is the language's comment marker (`"# "` for Nix, `";;; "` for
/// Guix). Dependency names are deliberately not translated: deb/rpm names are
/// not Nix attribute names or Guix variables, so a mapping would be a guess
/// (ADR-0030).
pub(crate) fn render_manifest_notes(manifest: &Manifest, prefix: &str, target: &str) -> String {
    let mut lines = vec![
        format!(
            "{prefix}Generated by arx-pack {} from a package manifest. Do not edit.",
            env!("CARGO_PKG_VERSION")
        ),
        prefix.trim_end().to_string(),
        format!("{prefix}These manifest fields have no direct {target} equivalent; they are"),
        format!("{prefix}recorded here verbatim so the translation stays auditable:"),
    ];
    let entries = [
        ("maintainer", vec![manifest.maintainer.clone()]),
        ("depends", manifest.depends.clone()),
        ("conflicts", manifest.conflicts.clone()),
        ("provides", manifest.provides.clone()),
        ("replaces", manifest.replaces.clone()),
        ("config files", manifest.config_files.clone()),
        ("maintainer scripts", script_names(manifest)),
    ];
    for (label, values) in entries {
        if !values.is_empty() {
            let joined = values
                .iter()
                .map(|value| comment_value(value))
                .collect::<Vec<_>>()
                .join(", ");
            lines.push(format!("{prefix}  {label}: {joined}"));
        }
    }
    lines.join("\n")
}

/// Keep one manifest value on one comment line.
fn comment_value(value: &str) -> String {
    value
        .chars()
        .map(|ch| if ch.is_control() { ' ' } else { ch })
        .collect()
}

/// Map a manifest architecture onto the Nix/Guix system name.
///
/// The returned names are the Nix system names. `build_guix` adjusts the two
/// that differ in Guix: 32-bit ARM is `armhf-linux`, and Guix has no s390x
/// system at all.
///
/// `None` means the package is architecture independent (`all`/`noarch`/`any`).
pub(crate) fn system_for_arch(arch: &str) -> Result<Option<&'static str>> {
    Ok(match arch {
        "x86_64" | "amd64" => Some("x86_64-linux"),
        "aarch64" | "arm64" => Some("aarch64-linux"),
        "i686" | "i386" | "x86" => Some("i686-linux"),
        "armv7" | "armv7h" | "armv7hl" | "armhf" => Some("armv7l-linux"),
        "ppc64le" | "ppc64el" => Some("powerpc64le-linux"),
        "s390x" => Some("s390x-linux"),
        "riscv64" => Some("riscv64-linux"),
        "all" | "noarch" | "any" => None,
        other => bail!(
            "unknown architecture {other:?} — accepted: x86_64/amd64, aarch64/arm64, \
             i686/i386/x86, armv7/armv7h/armv7hl/armhf, ppc64le/ppc64el, s390x, riscv64, \
             all/noarch"
        ),
    })
}

/// First line of a multi-line manifest description.
pub(crate) fn first_line(value: &str) -> &str {
    value.lines().next().unwrap_or("")
}

/// Split an SPDX expression into ids. `WITH` exception expressions stay whole,
/// so an id the license tables do not know resolves to "unmapped".
pub(crate) fn spdx_ids(raw: &str) -> Vec<&str> {
    raw.split(" OR ")
        .flat_map(|part| part.split(" AND "))
        .map(str::trim)
        .filter(|id| !id.is_empty())
        .collect()
}

/// Write a rendered definition into `out_dir`, returning its path.
pub(crate) fn write_definition(out_dir: &Path, filename: &str, body: &str) -> Result<PathBuf> {
    std::fs::create_dir_all(out_dir)
        .with_context(|| format!("creating output dir {}", out_dir.display()))?;
    let out_path = out_dir.join(filename);
    std::fs::write(&out_path, body).with_context(|| format!("writing {}", out_path.display()))?;
    Ok(out_path)
}

fn script_names(manifest: &Manifest) -> Vec<String> {
    [
        ("preinst", &manifest.scripts.preinst),
        ("postinst", &manifest.scripts.postinst),
        ("prerm", &manifest.scripts.prerm),
        ("postrm", &manifest.scripts.postrm),
    ]
    .into_iter()
    .filter(|(_, path)| path.is_some())
    .map(|(name, _)| name.to_string())
    .collect()
}

/// Quote one installed path as a `$out`-relative shell word.
///
/// The result is a double-quoted shell word with `$`, `` ` ``, `"`, and `\`
/// escaped, so it contains no `${` sequence and survives a Nix indented string
/// unchanged. Guix safety comes from `scheme_string`, which escapes the whole
/// script.
fn shell_path(rel: &str) -> Result<String> {
    if rel.contains(['\n', '\r', '\0']) {
        bail!("cannot render a shell path with control characters: {rel:?}");
    }
    let mut path = String::from("\"$out/");
    for ch in rel.chars() {
        match ch {
            '\\' => path.push_str("\\\\"),
            '"' => path.push_str("\\\""),
            '$' => path.push_str("\\$"),
            '`' => path.push_str("\\`"),
            _ => path.push(ch),
        }
    }
    path.push('"');
    Ok(path)
}

fn push_base64(out: &mut String, data: &[u8]) {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut column = 0;
    for chunk in data.chunks(3) {
        let second = chunk.get(1).copied().unwrap_or(0);
        let third = chunk.get(2).copied().unwrap_or(0);
        let bits = (u32::from(chunk[0]) << 16) | (u32::from(second) << 8) | u32::from(third);
        let symbols = [
            ALPHABET[(bits >> 18) as usize & 0x3f],
            ALPHABET[(bits >> 12) as usize & 0x3f],
            if chunk.len() > 1 {
                ALPHABET[(bits >> 6) as usize & 0x3f]
            } else {
                b'='
            },
            if chunk.len() > 2 {
                ALPHABET[bits as usize & 0x3f]
            } else {
                b'='
            },
        ];
        for symbol in symbols {
            out.push(char::from(symbol));
            column += 1;
            if column == BASE64_COLUMNS {
                out.push('\n');
                column = 0;
            }
        }
    }
    if column != 0 {
        out.push('\n');
    }
}

#[cfg(test)]
mod tests {
    use super::shell_path;

    #[test]
    fn shell_paths_expand_out_and_escape_shell_metacharacters() {
        assert_eq!(
            shell_path("usr/bin/hello").unwrap(),
            "\"$out/usr/bin/hello\""
        );
        assert_eq!(
            shell_path("opt/a b/$x/`y`/\"z\"/w\\v").unwrap(),
            "\"$out/opt/a b/\\$x/\\`y\\`/\\\"z\\\"/w\\\\v\""
        );
    }

    #[test]
    fn shell_paths_reject_line_breaks() {
        assert!(shell_path("usr/bin/bad\nname").is_err());
    }
}
